#!/usr/bin/env sh
# Combines supabase/migrations/*.sql into supabase/setup.sql: one file to paste
# into Supabase → SQL Editor on a NEW project. It runs in one transaction, so it
# either installs everything or changes nothing. Re-run after adding a migration.
set -e
cd "$(dirname "$0")/.."
out=supabase/setup.sql
{
  echo "-- The Pipeline Experiment — complete database setup (migrations 001–$(ls supabase/migrations | tail -1 | cut -c1-3))."
  echo "-- Generated by scripts/build-setup-sql.sh. Don't edit by hand."
  echo "-- Paste into Supabase → SQL Editor on a NEW project and click Run."
  echo "-- Already set up? Run only the migrations you haven't run yet instead."
  echo
  echo "begin;"
  for f in supabase/migrations/*.sql; do
    echo
    echo "-- ============================================================================"
    echo "-- $(basename "$f")"
    echo "-- ============================================================================"
    cat "$f"
    echo
  done
  echo "commit;"
} > "$out"
echo "wrote $out ($(wc -c < "$out") bytes)"
